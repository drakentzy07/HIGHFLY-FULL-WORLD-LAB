#!/usr/bin/env python3
"""HIGHFLY P39B — apply verified CC0 restoration and lazy load to ALL mob visuals.

One pass over EVERY mob_* VISUALS block in the staged v0.44.7 manifest.
Preserve original rigs when directly credited CC0, plus crab donors already
verified in P39A. NEVER interpret MIT source code as a blanket art license,
copy project-only/unverified art or change sim IDs, AI, quests, loot or player.

Instead of eager-loading hundreds of GLBs on mobile:
  * stage eligible original assets by exact original provenance
  * add their public/ paths to the direct media URL resolver
  * when a mob visual throws, kick ALL approved model/donor dependencies
  * rely on existing renderer's next-candidate retry gate after load completes
  * leave P36 NPC fallback and P38/P39A tutorial fixes intact.

Dry-run by default. Exact source anchors, validated original GLB hashes and
create-only copy; backup TS source files. Report unlicensed/unknown dependencies
for separate treatment. Requires P39A installed in Codespaces.
"""
from __future__ import annotations
import argparse
import csv
import hashlib
import json
import re
import sys
from collections import Counter
from datetime import datetime, timezone
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT/"scripts"))
import highfly_p9_private_build_smoke as p9
import highfly_p21_runtime_asset_recovery as p21
import highfly_p33_world_cc0_restore as p33
import highfly_p39a_crab_restore as p39a

ORIGINAL=p9.ORIGINAL
STAGE=p9.STAGE
OUT=ROOT/".workspace/reports/highfly-p39b-all-mobs"
MARK="HIGHFLY_P39B_ALL_MOBS_CC0_LAZY_LOAD"
MANIFEST="src/render/characters/manifest.ts"
SOURCES=("src/render/assets/media.ts",
         "src/render/characters/assets.ts",
         "src/render/characters/index.ts")
# Additional animation-donor GLBs were generated by MIT code using exactly
# the CC0 Quaternius CrabEnemy rig and independently verified/copied by P39A.
# Other generated donor GLBs are NEVER automatically treated as CC0.
P39A_DERIVED=set(p39a.MODELS[1:])
MAX_APPROVED_URLS=900
MAX_TOTAL_BYTES=1024*1024*1024


def hash_file(path:Path)->str:
    h=hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda:f.read(1<<20),b""):
            h.update(chunk)
    return h.hexdigest()


def mob_visual_dependencies(manifest:str)->dict[str,set[str]]:
    """Scan every mob_ visual definition, including nested animUrl arrays.

    This intentionally catalogs *referenced* assets, not all original media.
    Matches only literal .glb paths in the block; dynamic refs are reported
    separately in P39B_SUMMARY and remain subject to runtime diagnostics.
    """
    starts=list(re.finditer(r"(?m)^  (mob_[a-zA-Z0-9_]+): \{",manifest))
    all_defs=list(re.finditer(r"(?m)^  ([a-zA-Z0-9_]+): \{|^};",manifest))
    out={}
    for hit in starts:
        end=next((v.start() for v in all_defs if v.start()>hit.start()),len(manifest))
        block=manifest[hit.end():end]
        expanded=(block.replace("\${CREATURES}","models/creatures")
                   .replace("\${CHARS}","models/chars")
                   .replace("\${WEAPONS}","models/weapons")
                   .replace("\${PLAYER_CHARS}","models/chars/players"))
        refs=set(re.findall(
            r"models/(?:creatures|chars|weapons)/[A-Za-z0-9_./-]+\.glb",
            expanded,
        ))
        out[hit.group(1)]=refs
    return out


def classify(path:str, specs:dict)->dict:
    orig=ORIGINAL/"public"/path
    dest=STAGE/"public"/path
    legal=p33.exact_cc0_provenance(path,specs)
    derived=path in P39A_DERIVED
    if dest.is_symlink() or orig.is_symlink():
        status="BLOCK_SYMLINK"
    elif dest.is_file() and p21.check_binary(dest,path):
        if legal and p21.check_binary(orig,path) and hash_file(dest)==hash_file(orig):
            status="READY_CC0_EXISTING"
        elif derived and p21.check_binary(orig,path) and hash_file(dest)==hash_file(orig):
            status="READY_CRAB_DONOR_EXISTING"
        else:
            status="REVIEW_EXISTING_UNVERIFIED"
    elif dest.exists():
        status="BLOCK_BAD_STAGE_ASSET"
    elif legal and p21.check_binary(orig,path):
        status="RESTORE_EXACT_CC0"
    elif derived and p21.check_binary(orig,path):
        status="RESTORE_VERIFIED_P39A_CRAB_DONOR"
    elif legal:
        status="BLOCK_CC0_ORIGINAL_MISSING"
    else:
        status="BLOCK_UNVERIFIED_OR_PROJECT_ONLY"
    return {"path":path,"status":status,
            "licenseEvidence":legal or ("P39A_VERIFIED_QUATERNIUS_DONOR" if derived else "REVIEW"),
            "originalExists":orig.is_file(),"stageExists":dest.is_file(),
            "bytes":orig.stat().st_size if orig.is_file() and not orig.is_symlink() else 0}


def replace_exact(src,old,new,label):
    n=src.count(old)
    if n!=1:
        raise RuntimeError("P39B_SOURCE_ANCHOR_CHANGED "+label+" "+str(n))
    return src.replace(old,new,1)


def patch_sources(inputs, approved:list[str])->dict:
    if any(MARK in v for v in inputs.values()):
        raise RuntimeError("P39B_ALREADY_APPLIED")
    if not approved:
        raise RuntimeError("P39B_NO_VERIFIED_MOB_VISUALS")
    urls="\n".join("  '"+s+"'," for s in approved)
    media=replace_exact(
        inputs[SOURCES[0]],
        "  'models/creatures/crab_ability_anims.glb',",
        "  'models/creatures/crab_ability_anims.glb',\n"
        "  // "+MARK+": CC0 VERIFIED stage assets referenced by mob visuals.\n"+urls,
        "media-set-after-P39A-crab",
    )
    helper="""
// HIGHFLY_P39B_ALL_MOBS_CC0_LAZY_LOAD: only approved original CC0 assets.
// Missing GLBs are fetched lazily as the entity becomes relevant to the
// camera; unlike a global eager sweep, this cannot force 100+ mob rigs to
// compete with the NPCs/world on a mobile device at boot.
const HIGHFLY_P39B_MOB_CC0_URLS = new Set<string>([
"""+urls+"""
]);
export function ensureHighflyMobVisualAssets(key: string): void {
  if (!key.startsWith('mob_')) return;
  const def = VISUALS[key];
  if (!def) return;
  const dependencies = [
    def.url, ...(def.animUrls ?? []),
    ...(def.attach ?? []).map((held) => held.url),
  ];
  for (const url of new Set(dependencies)) {
    if (HIGHFLY_P39B_MOB_CC0_URLS.has(url)) ensureCharacterUrl(url);
  }
}
"""
    assets=replace_exact(
        inputs[SOURCES[1]],
        "export function startStreamedCharacterPreloads(): number {",
        helper+"\nexport function startStreamedCharacterPreloads(): number {",
        "assets-after-character-residency-helper",
    )
    index=replace_exact(
        inputs[SOURCES[2]],
        "import { type AssembleOptions, modularHeadFor } from './assets';",
        "import { type AssembleOptions, ensureHighflyMobVisualAssets, modularHeadFor } from './assets';",
        "index-assets-import",
    )
    index=replace_exact(
        index,
        "    // HIGHFLY_P36_NPC_FIXED_RIG_FALLBACK: NPC VISUAL ONLY.",
        "    // "+MARK+": re-arm the FULL body+animation dependency set\n"
        "    // for every mob; never alter its AI, templateId, loot or quest.\n"
        "    if (e.kind === 'mob') ensureHighflyMobVisualAssets(key);\n"
        "    // HIGHFLY_P36_NPC_FIXED_RIG_FALLBACK: NPC VISUAL ONLY.",
        "index-fail-soft-catch-before-NPC-fallback",
    )
    return dict(zip(SOURCES,(media,assets,index)))


def stage_preflight():
    p9.preflight(ORIGINAL,STAGE,p9.REPORT)
    main=STAGE/"src/main.ts"
    if "await preloadHighflyCrabAssets();" not in main.read_text(encoding="utf8"):
        raise RuntimeError("P39B_REQUIRES_P39A_CRAB_PRELOADER")
    original=(ORIGINAL/MANIFEST).read_text(encoding="utf8")
    stage=(STAGE/MANIFEST).read_text(encoding="utf8")
    if "shore_scuttler: 'mob_crab'" not in original or "shore_scuttler: 'mob_crab'" not in stage:
        raise RuntimeError("P39B_MOB_DISPATCH_MISSING")
    deps=mob_visual_dependencies(stage)
    if not deps or "mob_crab" not in deps:
        raise RuntimeError("P39B_CANNOT_SCAN_ORIGINAL_MOB_VISUALS")
    return deps


def run(apply=False):
    deps=stage_preflight()
    credits=p21.credits_state(ORIGINAL)
    specs=p21.build_spec_index(ORIGINAL,credits)
    referenced=sorted(set().union(*deps.values()))
    if not referenced:
        raise RuntimeError("P39B_NO_MOB_GLB_PATHS")
    rows=[classify(p,specs) for p in referenced]
    counts=dict(Counter(row["status"] for row in rows))
    eligible={"READY_CC0_EXISTING","READY_CRAB_DONOR_EXISTING",
              "RESTORE_EXACT_CC0","RESTORE_VERIFIED_P39A_CRAB_DONOR"}
    approved=sorted(row["path"] for row in rows if row["status"] in eligible)
    restores=[row for row in rows if row["status"].startswith("RESTORE_")]
    total_bytes=sum(row["bytes"] for row in restores)
    if len(approved)>MAX_APPROVED_URLS or total_bytes>MAX_TOTAL_BYTES:
        raise RuntimeError("P39B_LIMIT_EXCEEDED")
    inputs={}
    for rel in SOURCES:
        f=STAGE/rel
        if not f.is_file() or f.is_symlink():
            raise RuntimeError("P39B_PRIVATE_STAGE_SOURCE_MISSING "+rel)
        inputs[rel]=f.read_text(encoding="utf8")
    changed=patch_sources(inputs,approved)
    # Confirm every planned model isn't a symlink, including parents.
    for row in restores:
        original=ORIGINAL/"public"/row["path"]
        target=STAGE/"public"/row["path"]
        if not p33.ancestors_no_symlinks(original,ORIGINAL):
            raise RuntimeError("P39B_ORIGINAL_SYMLINK "+str(original))
        if not p33.ancestors_no_symlinks(target,STAGE):
            raise RuntimeError("P39B_STAGE_SYMLINK "+str(target))
    if apply:
        for rel in SOURCES:
            bak=OUT/"backups"/rel
            if bak.exists() or bak.is_symlink():
                raise RuntimeError("P39B_SOURCE_BACKUP_EXISTS "+str(bak))
        import shutil
        for rel in SOURCES:
            source=STAGE/rel
            backup=OUT/"backups"/rel
            backup.parent.mkdir(parents=True,exist_ok=True)
            shutil.copy2(source,backup)
            if hash_file(source)!=hash_file(backup):
                raise RuntimeError("P39B_BACKUP_HASH_MISMATCH "+rel)
        for row in restores:
            path=row["path"]
            src=ORIGINAL/"public"/path
            dst=STAGE/"public"/path
            if classify(path,specs)["status"]!=row["status"]:
                raise RuntimeError("P39B_ASSET_CHANGED_BEFORE_APPLY "+path)
            p33.stage_copy(src,dst,False,None)
            if hash_file(src)!=hash_file(dst) or not p21.check_binary(dst,path):
                raise RuntimeError("P39B_RESTORED_FILE_FAILED_INTEGRITY "+path)
        for rel in SOURCES:
            src=STAGE/rel
            if src.read_text(encoding="utf8")!=inputs[rel]:
                raise RuntimeError("P39B_SOURCE_CHANGED_BEFORE_APPLY "+rel)
            src.write_text(changed[rel],encoding="utf8")
    summary={
        "phase":"HIGHFLY_P39B_ALL_MONSTER_CC0_ASSET_AUDIT_AND_LAZY_FETCH",
        "mode":"APPLY" if apply else "DRY_RUN",
        "visualsParsed":len(deps),"dependencyReferences":len(referenced),
        "approvedForDirectRouteAndLazyFetch":len(approved),
        "restorable":len(restores),"restored":len(restores) if apply else 0,
        "remainingToLicenseOrRebuild":[r["path"] for r in rows if r["status"] not in eligible][:120],
        "blockedCount":len(rows)-len(approved),
        "statuses":counts,
        "allMonstersVisibleVerified":False,"noEagerFullWorldGLBLoading":True,
        "npcP38Preserved":True,"crabP39APreserved":True,"simAndLootChanged":False,
        "offlinePersistenceChanged":False,"inventoryIconsChanged":False,
        "timestampUtc":datetime.now(timezone.utc).isoformat(),
    }
    OUT.mkdir(parents=True,exist_ok=True)
    with (OUT/"P39B_ALL_MOB_DEPENDENCIES.csv").open("w",encoding="utf8",newline="") as f:
        writer=csv.DictWriter(f,fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)
    (OUT/"P39B_MOB_SUMMARY.json").write_text(
        json.dumps(summary,indent=2,ensure_ascii=False)+"\n",encoding="utf8")
    (OUT/"P39B_MOB_VISUAL_TO_GLBS.json").write_text(
        json.dumps({k:sorted(v) for k,v in deps.items()},indent=2)+"\n",encoding="utf8")
    print("[HIGHFLY] P39B ALL MOBS: "+json.dumps({
        "mode":summary["mode"],"visualsParsed":summary["visualsParsed"],
        "dependencies":summary["dependencyReferences"],
        "licensed":len(approved),"blocked":summary["blockedCount"],
        "restorable":len(restores),"restored":summary["restored"],
        "statuses":counts,"browserVerified":False},ensure_ascii=False))
    print("[HIGHFLY] P39B REPORT: "+str(OUT/"P39B_MOB_SUMMARY.json"))
    return summary


if __name__=="__main__":
    ap=argparse.ArgumentParser()
    ap.add_argument("--apply",action="store_true")
    args=ap.parse_args()
    run(args.apply)
